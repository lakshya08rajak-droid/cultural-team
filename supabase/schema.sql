-- 1. Ensure public.suggestions table exists
CREATE TABLE IF NOT EXISTS public.suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  title TEXT,
  category TEXT DEFAULT 'Other Ideas',
  description TEXT,
  upvotes INTEGER DEFAULT 0,
  is_approved BOOLEAN DEFAULT true,
  reviewed BOOLEAN DEFAULT false,
  suggestion TEXT
);

-- Ensure all columns exist on existing table without dropping or resetting data
ALTER TABLE public.suggestions ADD COLUMN IF NOT EXISTS title TEXT;
ALTER TABLE public.suggestions ADD COLUMN IF NOT EXISTS category TEXT DEFAULT 'Other Ideas';
ALTER TABLE public.suggestions ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE public.suggestions ADD COLUMN IF NOT EXISTS upvotes INTEGER DEFAULT 0;
ALTER TABLE public.suggestions ADD COLUMN IF NOT EXISTS is_approved BOOLEAN DEFAULT true;
ALTER TABLE public.suggestions ADD COLUMN IF NOT EXISTS reviewed BOOLEAN DEFAULT false;
ALTER TABLE public.suggestions ADD COLUMN IF NOT EXISTS suggestion TEXT;

-- 2. Performance Indexes
CREATE INDEX IF NOT EXISTS idx_suggestions_created_at ON public.suggestions(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_suggestions_upvotes ON public.suggestions(upvotes DESC);

-- 3. Database Constraints (<= 1,000 characters)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_suggestions_title_length') THEN
    ALTER TABLE public.suggestions ADD CONSTRAINT chk_suggestions_title_length 
      CHECK (title IS NULL OR (char_length(trim(title)) >= 2 AND char_length(title) <= 120));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_suggestions_desc_length') THEN
    ALTER TABLE public.suggestions ADD CONSTRAINT chk_suggestions_desc_length 
      CHECK (description IS NULL OR char_length(description) <= 1000);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_suggestions_raw_length') THEN
    ALTER TABLE public.suggestions ADD CONSTRAINT chk_suggestions_raw_length 
      CHECK (suggestion IS NULL OR (char_length(trim(suggestion)) >= 2 AND char_length(suggestion) <= 1000));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_suggestions_upvotes_non_neg') THEN
    ALTER TABLE public.suggestions ADD CONSTRAINT chk_suggestions_upvotes_non_neg 
      CHECK (upvotes >= 0);
  END IF;
END $$;

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.suggestions ENABLE ROW LEVEL SECURITY;

-- A. SELECT: Anonymous visitors can view approved suggestions
DROP POLICY IF EXISTS "Public can view approved suggestions" ON public.suggestions;
DROP POLICY IF EXISTS "Public can view suggestions" ON public.suggestions;
CREATE POLICY "Public can view suggestions"
  ON public.suggestions
  FOR SELECT
  TO public
  USING (COALESCE(is_approved, true) = true);

-- B. INSERT: Anonymous visitors can insert valid suggestions
DROP POLICY IF EXISTS "Public can insert suggestions" ON public.suggestions;
CREATE POLICY "Public can insert suggestions"
  ON public.suggestions
  FOR INSERT
  TO public
  WITH CHECK (
    (
      title IS NOT NULL AND 
      char_length(trim(title)) >= 2 AND 
      char_length(title) <= 120 AND
      (description IS NULL OR char_length(description) <= 1000)
    )
    OR
    (
      suggestion IS NOT NULL AND 
      char_length(trim(suggestion)) >= 2 AND 
      char_length(suggestion) <= 1000
    )
  );

-- C. Strict Security: Revoke public direct UPDATE and DELETE permissions
DROP POLICY IF EXISTS "Public can update upvotes" ON public.suggestions;
DROP POLICY IF EXISTS "Public can update suggestions" ON public.suggestions;
DROP POLICY IF EXISTS "Allow deletion of suggestions" ON public.suggestions;
DROP POLICY IF EXISTS "Public can delete suggestions" ON public.suggestions;

-- 5. Device-Bound Voter Tracking Table
CREATE TABLE IF NOT EXISTS public.suggestion_votes (
  suggestion_id BIGINT NOT NULL REFERENCES public.suggestions(id) ON DELETE CASCADE,
  voter_token TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  PRIMARY KEY (suggestion_id, voter_token)
);

CREATE INDEX IF NOT EXISTS idx_suggestion_votes_voter ON public.suggestion_votes(voter_token);

ALTER TABLE public.suggestion_votes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.suggestion_votes FROM anon, authenticated, public;
GRANT SELECT, INSERT, DELETE ON TABLE public.suggestion_votes TO service_role;

-- 6. Atomic Upvote Function
DROP FUNCTION IF EXISTS public.toggle_upvote(BIGINT, INT);
DROP FUNCTION IF EXISTS public.toggle_upvote(BIGINT, TEXT);

CREATE OR REPLACE FUNCTION public.toggle_upvote(p_id BIGINT, p_voter_token TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_new_votes INT;
  v_has_voted BOOLEAN;
  v_clean_token TEXT;
  v_active_votes_count INT;
BEGIN
  IF p_id IS NULL OR p_id <= 0 THEN
    RAISE EXCEPTION 'Invalid suggestion ID.';
  END IF;

  v_clean_token := trim(p_voter_token);
  IF v_clean_token IS NULL OR v_clean_token !~ '^voter_[a-zA-Z0-9_\-]{8,80}$' THEN
    RAISE EXCEPTION 'Invalid voter token format.';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.suggestions 
    WHERE id = p_id AND COALESCE(is_approved, true) = true
  ) THEN
    RAISE EXCEPTION 'Suggestion not found or unapproved.';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.suggestion_votes 
    WHERE suggestion_id = p_id AND voter_token = v_clean_token
  ) THEN
    -- UN-VOTE
    DELETE FROM public.suggestion_votes 
    WHERE suggestion_id = p_id AND voter_token = v_clean_token;

    UPDATE public.suggestions
    SET upvotes = GREATEST(0, COALESCE(upvotes, 1) - 1)
    WHERE id = p_id
    RETURNING upvotes INTO v_new_votes;

    v_has_voted := false;
  ELSE
    -- Rate check: max 50 active votes per device across platform
    SELECT count(*) INTO v_active_votes_count
    FROM public.suggestion_votes
    WHERE voter_token = v_clean_token;

    IF v_active_votes_count >= 50 THEN
      RAISE EXCEPTION 'Voting limit reached for this device.';
    END IF;

    -- UPVOTE
    INSERT INTO public.suggestion_votes (suggestion_id, voter_token)
    VALUES (p_id, v_clean_token)
    ON CONFLICT (suggestion_id, voter_token) DO NOTHING;

    UPDATE public.suggestions
    SET upvotes = COALESCE(upvotes, 0) + 1
    WHERE id = p_id
    RETURNING upvotes INTO v_new_votes;

    v_has_voted := true;
  END IF;

  RETURN jsonb_build_object(
    'id', p_id,
    'upvotes', COALESCE(v_new_votes, 0),
    'has_voted', v_has_voted
  );
END;
$$;

REVOKE ALL ON FUNCTION public.toggle_upvote(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.toggle_upvote(BIGINT, TEXT) TO anon, authenticated;

-- 7. Organizer Moderation RPCs
DROP FUNCTION IF EXISTS public.admin_delete_suggestion(BIGINT, TEXT);
CREATE OR REPLACE FUNCTION public.admin_delete_suggestion(p_id BIGINT, p_passcode TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_passcode IS NULL OR p_passcode <> 'cultural2026' THEN
    RAISE EXCEPTION 'Unauthorized: Invalid organizer passcode.';
  END IF;

  DELETE FROM public.suggestions WHERE id = p_id;
  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_delete_suggestion(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_delete_suggestion(BIGINT, TEXT) TO anon, authenticated;

DROP FUNCTION IF EXISTS public.admin_toggle_reviewed(BIGINT, TEXT);
CREATE OR REPLACE FUNCTION public.admin_toggle_reviewed(p_id BIGINT, p_passcode TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_current BOOLEAN;
BEGIN
  IF p_passcode IS NULL OR p_passcode <> 'cultural2026' THEN
    RAISE EXCEPTION 'Unauthorized: Invalid organizer passcode.';
  END IF;

  SELECT COALESCE(reviewed, false) INTO v_current FROM public.suggestions WHERE id = p_id;
  UPDATE public.suggestions
  SET reviewed = NOT v_current
  WHERE id = p_id;

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_toggle_reviewed(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_toggle_reviewed(BIGINT, TEXT) TO anon, authenticated;

